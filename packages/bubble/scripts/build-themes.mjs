// Builds themes/<tinai>/ from the package's own data, so the theme files
// never drift from the code:
//   theme.json   palette, motion, persona and karu, for any app or tool
//   theme.css    the --env-* variables in light and dark, for use without React
//   PERSONA.md   the persona, readable
//   sheet.html   one printable page per tinai (rendered to PDF by build-pdfs.mjs)
//
// Run from packages/bubble:
//   node --experimental-strip-types --import ./scripts/ts-resolve.mjs scripts/build-themes.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { ENVIRONMENTS } from "../src/tinai/environments.ts";
import { PERSONA_BY_KEY } from "../src/tinai/personas.ts";
import { KARU_BY_KEY, KARU_CATEGORIES, KARU_DRAFT } from "../src/lib/karupporul.ts";
import { YAZHI_AGENTS } from "../src/lib/agents.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "themes");

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** step response of a spring (mass 1), as an SVG path in a w×h box */
function springPath({ k, c }, w = 240, h = 80) {
  let x = 0, v = 0;
  const pts = [], n = 96, per = 1.6 / n, sub = 20, dt = per / sub;
  for (let i = 0; i <= n; i++) {
    pts.push(x);
    for (let j = 0; j < sub; j++) { v += (-k * (x - 1) - c * v) * dt; x += v * dt; }
  }
  const y = (q) => h - 8 - (h - 16) * (q / 1.25);
  return { d: pts.map((q, i) => `${i ? "L" : "M"}${((i / n) * w).toFixed(1)} ${y(q).toFixed(1)}`).join(""), base: y(1), overshoot: Math.max(0, Math.round((Math.max(...pts) - 1) * 100)) };
}

const index = [];

for (const env of ENVIRONMENTS) {
  const persona = PERSONA_BY_KEY[env.key];
  const karu = KARU_BY_KEY[env.key];
  const agents = YAZHI_AGENTS.filter((a) => a.tinai === env.key).map((a) => ({ id: a.id, name: a.name, ta: a.taName, home: a.home, rule: a.rule.replace(/\.$/, "") }));
  const dir = join(out, env.key);
  mkdirSync(dir, { recursive: true });

  const theme = {
    $schema: "yazhi.bubble.theme/v0",
    key: env.key,
    name: { ta: env.ta, en: env.en },
    landscape: env.landscape,
    signature: env.signature,
    mood: env.mood,
    useFor: env.useFor,
    apps: env.apps,
    agents,
    palette: env.palette,
    paletteLight: env.paletteLight,
    motion: { spring: env.spring, pace: env.pace, settleMs: env.settle, words: env.motionWords },
    light: env.light,
    pointer: env.pointerWords,
    persona,
    karu: { draft: KARU_DRAFT, time: karu.time, season: karu.season, land: karu.land, feeling: karu.uri, ...karu.karu },
    draft: "Persona names, voice and all Tamil text are drafts pending native review.",
  };
  writeFileSync(join(dir, "theme.json"), JSON.stringify(theme, null, 2) + "\n");

  const p = env.palette;
  const l = env.paletteLight;
  const pair = (k) => `light-dark(${l[k]}, ${p[k]})`;
  writeFileSync(
    join(dir, "theme.css"),
    `/* ${env.en} (${env.ta}) — ${env.signature}. Generated by scripts/build-themes.mjs; do not edit.
   Each colour is a light-dark() pair: it follows color-scheme, so set
   color-scheme: light dark (or light, or dark) on an ancestor. */
[data-tinai="${env.key}"], .tinai-${env.key} {
  --env-ground: ${pair("ground")};
  --env-surface: ${pair("surface")};
  --env-hi: ${pair("hi")};
  --env-edge: ${pair("edge")};
  --env-mid: ${pair("mid")};
  --env-lo: ${pair("lo")};
  --env-accent: ${pair("accent")};
  --env-text: ${pair("text")};
  --env-text-dim: ${pair("textDim")};
  --accent: var(--env-accent);
  --hairline-plate: var(--env-ground);
  --hairline-hi: var(--env-hi);
  --hairline-edge: var(--env-edge);
  --hairline-mid: var(--env-mid);
  --hairline-lo: var(--env-lo);
  --env-spring-k: ${env.spring.k};
  --env-spring-c: ${env.spring.c};
  --env-settle: ${env.settle}ms;
  --env-pace: ${env.pace};
}
`
  );

  const mc = persona.microcopy;
  const karuRows = KARU_CATEGORIES.map((c) => `| ${c.en} · ${c.ta} | ${karu.karu[c.key].map((k) => `${k.ta} (${k.en})`).join(", ")} |`).join("\n");
  writeFileSync(
    join(dir, "PERSONA.md"),
    `# ${env.ta} · ${env.en} — ${persona.name.ta} · ${persona.name.en}

> ${env.signature}. ${env.mood}.

**Draft:** the persona name, voice and every Tamil line are pending native review.

## Who
${persona.archetype}

**Voice:** ${persona.voice}
**Tone:** ${persona.tone.join(" · ")}

## Use it for
${env.useFor}. Default home of ${env.apps.join(" and ")}.${agents.length ? `\n\nYazhi agents in this landscape: ${agents.map((a) => `**${a.name}** (${a.ta}, ${a.home}) — ${a.rule}`).join("; ")}.` : ""}

## Interface copy
| Moment | தமிழ் | English |
|---|---|---|
| Empty | ${mc.empty.ta} | ${mc.empty.en} |
| Loading | ${mc.loading.ta} | ${mc.loading.en} |
| Success | ${mc.success.ta} | ${mc.success.en} |
| Error | ${mc.error.ta} | ${mc.error.en} |
| Confirm | ${mc.confirm.ta} | ${mc.confirm.en} |

## Do · Don't
${persona.do.map((d) => `- **Do** ${d.toLowerCase()}`).join("\n")}
${persona.dont.map((d) => `- **Don't** ${d.charAt(0).toLowerCase() + d.slice(1)}`).join("\n")}

## Look and motion
- **Light:** ${env.light}.
- **Motion:** ${env.motionWords} Spring k ${env.spring.k}, c ${env.spring.c}; settle ${env.settle} ms; ambient pace ×${env.pace}.
- **Pointer:** ${env.pointerWords}

| Token | Dark | Light |
|---|---|---|
${Object.entries(p).map(([k, v]) => `| \`--env-${k === "textDim" ? "text-dim" : k}\` | \`${v}\` | \`${l[k]}\` |`).join("\n")}

## Karupporul (draft)
${karu.time.en} · ${karu.season.en} · ${karu.land.en} — the feeling is ${karu.uri.en} (${karu.uri.ta}).

| Category | Items |
|---|---|
${karuRows}
`
  );

  const sp = springPath(env.spring);
  const swatches = (pal) =>
    Object.entries(pal)
      .map(([k, v]) => `<div class="sw"><span style="background:${v}"></span><b>${k === "textDim" ? "text-dim" : k}</b><i>${v}</i></div>`)
      .join("");
  const copy = Object.entries(mc)
    .map(([k, l]) => `<tr><th>${k}</th><td lang="ta">${esc(l.ta)}</td><td>${esc(l.en)}</td></tr>`)
    .join("");
  const karuMini = ["bird", "beast", "flower", "tree", "drum", "yazh", "pann"]
    .map((c) => `<li><b>${KARU_CATEGORIES.find((x) => x.key === c).en}</b> <span lang="ta">${esc(karu.karu[c].map((k) => k.ta).join(" · "))}</span></li>`)
    .join("");
  writeFileSync(
    join(dir, "sheet.html"),
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${env.en} theme sheet</title>
<link href="https://fonts.googleapis.com/css2?family=Noto+Sans+Tamil:wght@400;600&family=Playfair+Display:wght@700;900&family=EB+Garamond:wght@400;600&display=swap" rel="stylesheet">
<style>
@page { size: A4 landscape; margin: 0 }
*{box-sizing:border-box;margin:0;padding:0}
body{width:297mm;height:210mm;background:${p.ground};color:${p.text};font:12px/1.5 "EB Garamond",serif;padding:14mm 16mm;-webkit-print-color-adjust:exact;print-color-adjust:exact}
[lang=ta]{font-family:"Noto Sans Tamil",sans-serif;letter-spacing:0}
.top{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:1px solid ${p.mid};padding-bottom:6mm}
.eyebrow{font:10px/1 ui-monospace,monospace;text-transform:uppercase;letter-spacing:.14em;color:${p.accent}}
h1{font:900 34px/1.1 "Playfair Display",serif;margin-top:3mm}
h1 [lang=ta]{font-weight:600;font-size:38px;margin-right:4mm}
.persona{text-align:right}
.persona h2{font:700 20px/1.2 "Playfair Display",serif}
.persona p{color:${p.textDim}}
.grid{display:grid;grid-template-columns:1.1fr 1fr 1fr;gap:9mm;margin-top:7mm}
h3{font:10px/1 ui-monospace,monospace;text-transform:uppercase;letter-spacing:.12em;color:${p.textDim};margin-bottom:3mm}
.sw-grid{display:grid;grid-template-columns:repeat(5,1fr);gap:2mm 2.5mm}
.sw span{display:block;height:7mm;border:1px solid ${p.mid};border-radius:2mm}
.sw b{display:block;font:10px ui-monospace,monospace;margin-top:1mm}
.sw i{font:9px ui-monospace,monospace;color:${p.textDim};font-style:normal;text-transform:uppercase}
table{border-collapse:collapse;width:100%}
td,th{border-top:1px solid ${p.lo};padding:1.6mm 1.5mm 1.6mm 0;vertical-align:top;text-align:left}
th{font:9px ui-monospace,monospace;text-transform:uppercase;color:${p.accent};width:16mm}
.small{font-size:11px;color:${p.textDim}}
ul{list-style:none}li{border-top:1px solid ${p.lo};padding:1.4mm 0}li b{font:9px ui-monospace,monospace;text-transform:uppercase;color:${p.accent};display:inline-block;width:14mm}
.rule{margin-top:3mm;font-size:11px}.rule b{color:${p.hi};font:10px ui-monospace,monospace;text-transform:uppercase;margin-right:2mm}
svg{width:100%;height:auto;display:block}
.foot{position:absolute;bottom:9mm;left:16mm;right:16mm;display:flex;justify-content:space-between;font:9px ui-monospace,monospace;color:${p.textDim}}
.mark circle{fill:${p.text}}
</style></head><body>
<div class="top">
  <div><p class="eyebrow">Bubble UI · Tinai theme · ${esc(env.landscape)}</p><h1><span lang="ta">${env.ta}</span>${env.en}</h1><p class="small" style="margin-top:2mm">${esc(env.signature)}. ${esc(env.mood)}.</p></div>
  <div class="persona"><p class="eyebrow">Persona</p><h2><span lang="ta">${persona.name.ta}</span> · ${persona.name.en}</h2><p style="max-width:95mm;margin-left:auto">${esc(persona.archetype)}</p><p class="small">${persona.tone.join(" · ")}</p></div>
</div>
<div class="grid">
  <section>
    <h3>Palette · dark</h3><div class="sw-grid">${swatches(p)}</div>
    <h3 style="margin-top:4mm">Palette · light</h3><div class="sw-grid">${swatches(l)}</div>
    <h3 style="margin-top:6mm">Motion · spring k ${env.spring.k} c ${env.spring.c} · overshoot ${sp.overshoot}% · settle ${env.settle}ms</h3>
    <svg viewBox="0 0 240 80"><line x1="0" x2="240" y1="${sp.base.toFixed(1)}" y2="${sp.base.toFixed(1)}" stroke="${p.lo}" stroke-dasharray="1 3"/><path d="${sp.d}" fill="none" stroke="${p.hi}" stroke-width="1"/></svg>
    <p class="small">${esc(env.motionWords)} ${esc(env.pointerWords)}</p>
  </section>
  <section>
    <h3>Voice</h3><p>${esc(persona.voice)}</p>
    <h3 style="margin-top:5mm">Interface copy (draft)</h3><table>${copy}</table>
  </section>
  <section>
    <h3>Use for</h3><p>${esc(env.useFor)}.</p><p class="small">Home of ${esc(env.apps.join(", "))}.</p>
    ${agents.map((a) => `<p class="rule"><b>${esc(a.name)}</b><span lang="ta">${esc(a.ta)}</span> — ${esc(a.rule)}</p>`).join("")}
    <h3 style="margin-top:5mm">Karupporul (draft)</h3><ul>${karuMini}</ul>
    <h3 style="margin-top:5mm">Do · Don't</h3>
    <p class="small">${persona.do.map(esc).join(" · ")}</p><p class="small" style="margin-top:1mm">Not: ${persona.dont.map(esc).join(" · ")}</p>
  </section>
</div>
<div class="foot"><span><svg class="mark" viewBox="0 0 100 100" style="width:5mm;display:inline-block;vertical-align:middle"><circle cx="30.8" cy="30.6" r="12.3"/><circle cx="65.2" cy="26.9" r="16.3"/><circle cx="47.2" cy="67.4" r="22"/></svg> யாழி · Bubble UI</span><span>Persona and Tamil text are drafts pending native review · generated from packages/bubble</span></div>
</body></html>
`
  );

  index.push({ key: env.key, ta: env.ta, en: env.en, persona: persona.name, accent: p.accent, accentLight: l.accent, files: ["theme.json", "theme.css", "PERSONA.md", "sheet.html"].map((f) => `${env.key}/${f}`) });
}

writeFileSync(join(out, "index.json"), JSON.stringify(index, null, 2) + "\n");
writeFileSync(
  join(out, "all.css"),
  ENVIRONMENTS.map((e) => `@import "./${e.key}/theme.css";`).join("\n") + "\n"
);
console.log(`built ${index.length} themes → ${out}`);
