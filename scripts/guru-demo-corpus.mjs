// Builds apps/guru/demo-corpus.ts — the Guru demo's only source of answers —
// from the guru-tnpsc chunk file (tools/chunk_lessons.py output).
//
//   node scripts/guru-demo-corpus.mjs /path/to/guru-tnpsc/chunks/guru-tnpsc-chunks.jsonl
//
// Keeps the study chunks (overview, notes, key facts, mind map). MCQs,
// previous-year-style questions, source lists and review flags stay out:
// the demo answers from notes, it does not set questions. Text is copied
// verbatim (NFC); nothing is written or summarised here.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/guru-demo-corpus.mjs <guru-tnpsc-chunks.jsonl>");
  process.exit(1);
}
const KEEP = new Set(["overview", "notes", "key_facts", "mind_map"]);
const raw = readFileSync(src, "utf8");
const rows = raw.split("\n").filter(Boolean).map((l) => JSON.parse(l)).filter((c) => KEEP.has(c.content_type));

const chunks = rows.map((c) => ({
  id: c.chunk_id,
  lesson: c.lesson_id,
  file: c.lesson_file,
  titleTa: c.title_ta.normalize("NFC"),
  titleEn: c.title_en.normalize("NFC"),
  section: c.section.normalize("NFC"),
  subsection: c.subsection ? c.subsection.normalize("NFC") : null,
  type: c.content_type,
  levels: c.levels,
  exam: c.exams[0],
  sources: c.source_ids,
  review: !!c.review_required,
  text: c.text.normalize("NFC"),
}));

const digest = createHash("sha1").update(raw).digest("hex").slice(0, 12);
const out = `/* GENERATED by scripts/guru-demo-corpus.mjs — do not edit by hand.
   Source: guru-tnpsc corpus v0.1-draft (chunks file sha1 ${digest}),
   ${chunks.length} study chunks from ${new Set(chunks.map((c) => c.lesson)).size} lessons.
   Text is verbatim from the Guru lesson notes; † marks a line that still
   needs faculty review. */

export type DemoChunkType = "overview" | "notes" | "key_facts" | "mind_map";

export interface DemoChunk {
  id: string;
  lesson: string;
  file: string;
  titleTa: string;
  titleEn: string;
  section: string;
  subsection: string | null;
  type: DemoChunkType;
  levels: string[];
  exam: string;
  sources: string[];
  review: boolean;
  text: string;
}

export const DEMO_CORPUS_VERSION = "0.1-draft+${digest}";

export const DEMO_CORPUS: DemoChunk[] = ${JSON.stringify(chunks, null, 1)};
`;
writeFileSync(new URL("../apps/guru/demo-corpus.ts", import.meta.url), out);
console.log(`wrote apps/guru/demo-corpus.ts — ${chunks.length} chunks`);
